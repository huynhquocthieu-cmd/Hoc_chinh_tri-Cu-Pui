-- 4. Phan quyen doc ho so: hoc vien chi doc ho so cua minh; quan tri vien doc duoc tat ca.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS profiles_read_self_or_admin ON public.profiles;
CREATE POLICY profiles_read_self_or_admin
  ON public.profiles FOR SELECT TO authenticated
  USING (id = auth.uid() OR public.is_admin());
GRANT SELECT ON public.profiles TO authenticated;

-- 5. Nhat ky tham gia hoc: mot dong moi cho moi lan dang nhap/dang ky.
CREATE TABLE IF NOT EXISTS public.participation_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT NOT NULL,
  display_name TEXT NOT NULL DEFAULT '',
  rank TEXT NOT NULL DEFAULT '',
  unit TEXT NOT NULL DEFAULT '',
  event_type TEXT NOT NULL DEFAULT 'login'
    CHECK (event_type IN ('register', 'login')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS participation_events_created_at_idx
  ON public.participation_events (created_at DESC);
CREATE INDEX IF NOT EXISTS participation_events_user_id_idx
  ON public.participation_events (user_id);

ALTER TABLE public.participation_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS participation_student_insert ON public.participation_events;
CREATE POLICY participation_student_insert
  ON public.participation_events FOR INSERT TO authenticated
  WITH CHECK (
    user_id = auth.uid()
    AND EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND p.role = 'student'
    )
  );

DROP POLICY IF EXISTS participation_admin_read ON public.participation_events;
CREATE POLICY participation_admin_read
  ON public.participation_events FOR SELECT TO authenticated
  USING (public.is_admin());

GRANT INSERT, SELECT ON public.participation_events TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.participation_events_id_seq TO authenticated;

-- 6. Bat realtime de trang quan tri tu cap nhat danh sach.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'participation_events'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.participation_events;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'profiles'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.profiles;
  END IF;
END $$;
